const DICTS: Record<Language, Record<StringKey, string>> = { en, id, tr };
const LOCALES: Record<Language, string> = { en: 'en-GB', id: 'id-ID', tr: 'tr-TR' };

export const LANGUAGES: { value: Language; label: string }[] = [
  { value: 'en', label: 'English' },
  { value: 'id', label: 'Indonesia' },
  { value: 'tr', label: 'Türkçe' },
];

export const translate = (lang: Language, key: StringKey, params?: Record<string, string | number>): string => {
  let s = (DICTS[lang] || en)[key] ?? en[key] ?? key;
  if (params) Object.entries(params).forEach(([k, v]) => (s = s.split(`{${k}}`).join(String(v))));
  return s;
};

export const useT = () => {
  const { state } = useApp();
  const lang = state.settings.language;
  const locale = LOCALES[lang];
  return {
    lang,
    t: (key: StringKey, params?: Record<string, string | number>) => translate(lang, key, params),
    formatNumber: (n: number) => n.toLocaleString(locale),
    formatDay: (ts: number) => new Date(ts).toLocaleDateString(locale, { weekday: 'long', day: 'numeric', month: 'long' }),
    formatTime: (d: Date) => d.toLocaleTimeString(locale, { hour: '2-digit', minute: '2-digit' }),
    formatClock: (h: number, m: number) => new Date(2000, 0, 1, h, m).toLocaleTimeString(locale, { hour: '2-digit', minute: '2-digit' }),
    formatDateTime: (ts: number) =>
      new Date(ts).toLocaleString(locale, { day: 'numeric', month: 'short', hour: '2-digit', minute: '2-digit' }),
    formatWeekday: (ts: number) => new Date(ts).toLocaleDateString(locale, { weekday: 'short' }),
    formatMonth: (ts: number) => new Date(ts).toLocaleDateString(locale, { month: 'short' }),
    // 2023-01-01 was a Sunday, so day 0 = Sunday.
    weekdayShort: (day: number) => new Date(2023, 0, 1 + day).toLocaleDateString(locale, { weekday: 'short' }),
  };
};
